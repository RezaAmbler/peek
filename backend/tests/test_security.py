"""
Tests for password hashing and JWT helpers.

These guard the bcrypt migration: PEEK used to hash via passlib's CryptContext,
which silently truncated passwords to bcrypt's 72-byte limit. bcrypt>=5 raises
instead, so security.py truncates explicitly. Hashes written by the old passlib
stack must keep verifying, hence the hard-coded legacy hashes below.
"""

from datetime import timedelta

import bcrypt
import pytest
from jose import jwt

from app.core import security
from app.core.config import settings
from app.core.security import (
    BCRYPT_MAX_BYTES,
    create_access_token,
    decode_access_token,
    get_password_hash,
    password_needs_rehash,
    verify_password,
)
from app.schemas.user import validate_password_strength

# Generated by the previous stack (passlib 1.7.4 + bcrypt 4.3.0).
LEGACY_HASHES = {
    "admin": "$2b$12$gMOMbEysqTBmdziuUZ7l/OAQNxWg.BxpXiln0VxZfNMc/U10zolpe",
    "correct horse battery staple": "$2b$12$UfYM7a1W0dAEmDMRPBtjou7xgWTFdCAjAhOJiyEmtRlz0dicNr89C",
    "pÄssw0rd-ünïcode": "$2b$12$sCe1sxsmoJfqdbtjhz6Tfuak4Eo2.LP9dKzFRhiJqixwqn6crIqLi",
}


class TestPasswordHashing:
    def test_roundtrip(self):
        hashed = get_password_hash("admin")
        assert hashed.startswith("$2b$")
        assert verify_password("admin", hashed)

    def test_rejects_wrong_password(self):
        assert not verify_password("nope", get_password_hash("admin"))

    def test_salted_hashes_are_unique(self):
        assert get_password_hash("admin") != get_password_hash("admin")

    @pytest.mark.parametrize("password", list(LEGACY_HASHES))
    def test_verifies_legacy_passlib_hashes(self, password):
        """Existing users must not be locked out by the passlib removal."""
        assert verify_password(password, LEGACY_HASHES[password])

    def test_rejects_wrong_password_against_legacy_hash(self):
        assert not verify_password("wrong", LEGACY_HASHES["admin"])

    def test_unicode_password_roundtrip(self):
        password = "pÄssw0rd-ünïcode"
        assert verify_password(password, get_password_hash(password))

    def test_long_password_does_not_raise(self):
        """bcrypt>=5 raises on >72 bytes; we truncate like passlib did."""
        hashed = get_password_hash("y" * 100)
        assert verify_password("y" * 100, hashed)

    def test_long_password_truncated_at_bcrypt_limit(self):
        """Documents inherited behaviour: bytes past the limit are ignored."""
        hashed = get_password_hash("y" * BCRYPT_MAX_BYTES)
        assert verify_password("y" * (BCRYPT_MAX_BYTES + 10), hashed)

    def test_malformed_stored_hash_returns_false(self):
        """A corrupt hash is a failed login, not a 500."""
        assert not verify_password("admin", "not-a-bcrypt-hash")

    @pytest.mark.parametrize("stored", [
        "",                                            # empty
        "$2b$12$xxxxxxxxxx",                           # truncated after the cost (panicked on bcrypt 4.2)
        LEGACY_HASHES["admin"][:40],                   # truncated digest
        LEGACY_HASHES["admin"][:-1],                   # one character short
        LEGACY_HASHES["admin"] + "A",                  # one character too long
        LEGACY_HASHES["admin"].replace("$12$", "$99$"),  # cost out of range
        LEGACY_HASHES["admin"].replace("$2b$", "$2z$"),  # unknown variant
        "$2b$12$" + "é" * 53,                          # non-ASCII body
        "$2b$12$" + "!" * 53,                          # invalid base64 alphabet
        LEGACY_HASHES["admin"] + "\n",                 # trailing newline from a bad import
        "plaintext-password",
        None,
        12345,
        b"$2b$12$gMOMbEysqTBmdziuUZ7l/OAQNxWg.BxpXiln0VxZfNMc/U10zolpe",
    ])
    def test_unusable_stored_hash_never_raises(self, stored):
        """Truncated / malformed / wrong-type hashes are a failed login, never an exception."""
        assert verify_password("admin", stored) is False

    @pytest.mark.parametrize("password", [None, 123, b"admin"])
    def test_non_string_password_returns_false(self, password):
        assert verify_password(password, LEGACY_HASHES["admin"]) is False

    def test_bcrypt_errors_are_swallowed(self, monkeypatch):
        """Whatever bcrypt raises for a hash that passed the shape check is a failed login."""
        def explode(password, hashed):
            raise ValueError("Invalid salt")
        monkeypatch.setattr(security.bcrypt, "checkpw", explode)
        assert verify_password("admin", LEGACY_HASHES["admin"]) is False

    def test_bcrypt_panic_is_swallowed_but_other_base_exceptions_propagate(self, monkeypatch):
        """pyo3's PanicException derives from BaseException, not Exception."""
        class PanicException(BaseException):
            pass

        def panic(password, hashed):
            raise PanicException("range end index 22 out of range")
        monkeypatch.setattr(security.bcrypt, "checkpw", panic)
        assert verify_password("admin", LEGACY_HASHES["admin"]) is False

        def interrupt(password, hashed):
            raise KeyboardInterrupt()
        monkeypatch.setattr(security.bcrypt, "checkpw", interrupt)
        with pytest.raises(KeyboardInterrupt):
            verify_password("admin", LEGACY_HASHES["admin"])

    def test_dummy_timing_hash_is_usable(self):
        """auth.py verifies against this constant for unknown usernames.

        It must be a well-formed hash so the unknown-user path costs a full
        bcrypt verification instead of failing fast on the shape check.
        """
        from app.routers.auth import DUMMY_PASSWORD_HASH
        assert security._hash_cost(DUMMY_PASSWORD_HASH) == 12
        calls = []
        real_checkpw = bcrypt.checkpw

        def counting_checkpw(password, hashed):
            calls.append(hashed)
            return real_checkpw(password, hashed)
        with pytest.MonkeyPatch.context() as patch:
            patch.setattr(security.bcrypt, "checkpw", counting_checkpw)
            assert not verify_password("anything", DUMMY_PASSWORD_HASH)
        assert calls == [DUMMY_PASSWORD_HASH.encode()]


class TestPinnedBcrypt:
    """Behaviours of the pinned bcrypt release that security.py relies on."""

    def test_installed_version_matches_the_pin(self):
        from pathlib import Path
        requirements = Path(__file__).resolve().parents[1] / "requirements.txt"
        pinned = [line.split("==")[1].strip() for line in requirements.read_text().splitlines()
                  if line.startswith("bcrypt==")]
        assert pinned == [bcrypt.__version__]

    def test_raises_instead_of_truncating_long_input(self):
        with pytest.raises(ValueError):
            bcrypt.hashpw(b"x" * 73, bcrypt.gensalt(4))

    def test_malformed_hash_raises_value_error(self):
        for stored in (b"", b"not-a-bcrypt-hash", b"$2b$12$xxxxxxxxxx"):
            with pytest.raises(ValueError):
                bcrypt.checkpw(b"a", stored)

    @pytest.mark.parametrize("prefix", ["$2a$", "$2y$"])
    def test_legacy_prefixes_verify(self, prefix):
        hashed = prefix + LEGACY_HASHES["admin"][4:]
        assert verify_password("admin", hashed)
        assert not verify_password("wrong", hashed)


class TestNulBytes:
    def test_nul_byte_password_does_not_raise_and_is_not_truncated(self):
        hashed = get_password_hash("a\x00b")
        assert verify_password("a\x00b", hashed)
        assert not verify_password("a", hashed)        # not cut at the NUL
        assert not verify_password("a\x00c", hashed)   # bytes after the NUL count

    def test_nul_byte_login_attempt_is_a_plain_mismatch(self):
        assert verify_password("admin\x00", LEGACY_HASHES["admin"]) is False
        assert verify_password("\x00", LEGACY_HASHES["admin"]) is False

    def test_new_passwords_with_nul_are_rejected(self):
        with pytest.raises(ValueError, match="NUL"):
            validate_password_strength("Passw0rd\x00x")


class TestTruncation:
    def test_ascii_passwords_are_cut_at_72_bytes(self):
        assert security._encode("y" * 100) == b"y" * 72
        assert security._encode("y" * 72) == b"y" * 72

    def test_multibyte_character_is_not_split(self):
        # 71 ASCII bytes + a 2-byte character straddling the limit
        password = "a" * 71 + "é" + "tail"
        encoded = security._encode(password)
        assert encoded == b"a" * 71
        encoded.decode("utf-8")  # still valid UTF-8
        # 70 ASCII bytes + a 4-byte emoji straddling the limit
        assert security._encode("a" * 70 + "\U0001F600" + "x") == b"a" * 70
        # A character that ends exactly on the limit is kept whole
        assert security._encode("a" * 70 + "é" + "x") == ("a" * 70 + "é").encode()

    def test_legacy_truncation_splits_the_character(self):
        password = "a" * 71 + "é"
        assert security._encode_legacy(password) == b"a" * 71 + b"\xc3"

    def test_hash_of_straddling_password_verifies(self):
        password = "a" * 71 + "é" + "tail"
        assert verify_password(password, get_password_hash(password))

    def test_hash_created_with_legacy_byte_truncation_still_verifies(self):
        """Hashes written by passlib / PEEK <= 2.2.1 cut mid-character; they must keep working."""
        password = "a" * 71 + "é" + "tail"
        legacy_hash = bcrypt.hashpw(password.encode("utf-8")[:72], bcrypt.gensalt(4)).decode()
        assert verify_password(password, legacy_hash)
        assert not verify_password("a" * 71 + "x" + "tail", legacy_hash)

    def test_new_passwords_over_72_bytes_are_rejected(self):
        validate_password_strength("Aa1" + "x" * 69)  # exactly 72 bytes
        with pytest.raises(ValueError, match="72 bytes"):
            validate_password_strength("Aa1" + "x" * 70)
        with pytest.raises(ValueError, match="72 bytes"):
            validate_password_strength("Aa1" + "é" * 35)  # 38 characters, 73 bytes


class TestRehash:
    def test_cost_comes_from_settings(self, monkeypatch):
        monkeypatch.setattr(settings, "BCRYPT_ROUNDS", 5)
        assert get_password_hash("pw").startswith("$2b$05$")

    def test_needs_rehash_when_cost_differs_or_variant_is_legacy(self, monkeypatch):
        monkeypatch.setattr(settings, "BCRYPT_ROUNDS", 5)
        assert not password_needs_rehash(get_password_hash("pw"))
        assert password_needs_rehash(LEGACY_HASHES["admin"])  # cost 12
        monkeypatch.setattr(settings, "BCRYPT_ROUNDS", 12)
        assert not password_needs_rehash(LEGACY_HASHES["admin"])
        assert password_needs_rehash("$2a$" + LEGACY_HASHES["admin"][4:])

    @pytest.mark.parametrize("stored", ["", "garbage", None, "$2b$12$short"])
    def test_malformed_hash_never_needs_rehash(self, stored):
        assert password_needs_rehash(stored) is False

    def test_rounds_setting_is_validated(self):
        from app.core.config import Settings
        for bad in (3, 32):
            with pytest.raises(ValueError):
                Settings(SECRET_KEY=settings.SECRET_KEY, BCRYPT_ROUNDS=bad)

    @pytest.mark.parametrize("algorithm", ["none", "None", "RS256", ""])
    def test_jwt_algorithm_is_allow_listed(self, algorithm):
        from app.core.config import Settings
        with pytest.raises(ValueError):
            Settings(SECRET_KEY=settings.SECRET_KEY, ALGORITHM=algorithm)


class TestAccessToken:
    def test_roundtrip(self):
        token = create_access_token({"sub": "user-1"})
        assert decode_access_token(token)["sub"] == "user-1"

    def test_invalid_token_returns_none(self):
        assert decode_access_token("garbage.token.value") is None

    def test_rejects_forged_signature(self):
        forged = jwt.encode(
            {"sub": "attacker"}, "a-different-secret", algorithm=settings.ALGORITHM
        )
        assert decode_access_token(forged) is None

    def test_expired_token_returns_none(self):
        token = create_access_token({"sub": "u"}, expires_delta=timedelta(seconds=-1))
        assert decode_access_token(token) is None
