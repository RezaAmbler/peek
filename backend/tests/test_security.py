"""
Tests for password hashing and JWT helpers.

These guard the bcrypt migration: PEEK used to hash via passlib's CryptContext,
which silently truncated passwords to bcrypt's 72-byte limit. bcrypt>=5 raises
instead, so security.py truncates explicitly. Hashes written by the old passlib
stack must keep verifying, hence the hard-coded legacy hashes below.
"""

from datetime import timedelta

import pytest
from jose import jwt

from app.core.config import settings
from app.core.security import (
    BCRYPT_MAX_BYTES,
    create_access_token,
    decode_access_token,
    get_password_hash,
    verify_password,
)

# Generated by the previous stack (passlib 1.7.4 + bcrypt 4.3.0).
LEGACY_HASHES = {
    "admin": "$2b$12$gMOMbEysqTBmdziuUZ7l/OAQNxWg.BxpXiln0VxZfNMc/U10zolpe",
    "correct horse battery staple": "$2b$12$UfYM7a1W0dAEmDMRPBtjou7xgWTFdCAjAhOJiyEmtRlz0dicNr89C",
    "pÄssw0rd-ünïcode": "$2b$12$sCe1sxsmoJfqdbtjhz6Tfuak4Eo2.LP9dKzFRhiJqixwqn6crIqLi",
}


class TestPasswordHashing:
    def test_roundtrip(self):
        hashed = get_password_hash("admin")
        assert hashed.startswith("$2b$")
        assert verify_password("admin", hashed)

    def test_rejects_wrong_password(self):
        assert not verify_password("nope", get_password_hash("admin"))

    def test_salted_hashes_are_unique(self):
        assert get_password_hash("admin") != get_password_hash("admin")

    @pytest.mark.parametrize("password", list(LEGACY_HASHES))
    def test_verifies_legacy_passlib_hashes(self, password):
        """Existing users must not be locked out by the passlib removal."""
        assert verify_password(password, LEGACY_HASHES[password])

    def test_rejects_wrong_password_against_legacy_hash(self):
        assert not verify_password("wrong", LEGACY_HASHES["admin"])

    def test_unicode_password_roundtrip(self):
        password = "pÄssw0rd-ünïcode"
        assert verify_password(password, get_password_hash(password))

    def test_long_password_does_not_raise(self):
        """bcrypt>=5 raises on >72 bytes; we truncate like passlib did."""
        hashed = get_password_hash("y" * 100)
        assert verify_password("y" * 100, hashed)

    def test_long_password_truncated_at_bcrypt_limit(self):
        """Documents inherited behaviour: bytes past the limit are ignored."""
        hashed = get_password_hash("y" * BCRYPT_MAX_BYTES)
        assert verify_password("y" * (BCRYPT_MAX_BYTES + 10), hashed)

    def test_malformed_stored_hash_returns_false(self):
        """A corrupt hash is a failed login, not a 500."""
        assert not verify_password("admin", "not-a-bcrypt-hash")

    def test_dummy_timing_hash_is_usable(self):
        """auth.py verifies against this constant for unknown usernames."""
        dummy = "$2b$12$LQv3c1yqBWVHxkd0LHAkCOYz6TtxMQJqhN8/X4.O/4xJa.r9D8mGi"
        assert not verify_password("anything", dummy)


class TestAccessToken:
    def test_roundtrip(self):
        token = create_access_token({"sub": "user-1"})
        assert decode_access_token(token)["sub"] == "user-1"

    def test_invalid_token_returns_none(self):
        assert decode_access_token("garbage.token.value") is None

    def test_rejects_forged_signature(self):
        forged = jwt.encode(
            {"sub": "attacker"}, "a-different-secret", algorithm=settings.ALGORITHM
        )
        assert decode_access_token(forged) is None

    def test_expired_token_returns_none(self):
        token = create_access_token({"sub": "u"}, expires_delta=timedelta(seconds=-1))
        assert decode_access_token(token) is None
